#!/usr/bin/env python3
"""Generate import-only movie metadata from the retained owned File1 inventory."""
import hashlib,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()

def main():
    routes=ROOT/'build-native-sjuni/movie-routes/file1-v1/members.json'
    counts=ROOT/'build-native-sjuni/movie-matrix/catalog-counts-v1/counts.json'
    inventory=ROOT/'build-native-sjuni/audio-asset-inventory/file1-v1/members.json'
    expected={routes:'a5564bca8c19efa018b8acedeb19f400c698c630dd03678702329bdd10473d93',counts:'c255a4c59bd5fd6e9f6fbadf0092a41b38d4afc22d079287a3755ecfaa6d11bd',inventory:'276264fd0f5d14e8e0ef1e17f008560d611c6ca30c2ad811259a004b7a54fbc2'}
    for path,digest in expected.items():
        if sha(path)!=digest:raise ValueError('Owned inventory identity drift: '+str(path))
    rows=json.loads(routes.read_bytes());pictures={tuple(r['asset']):r['pictures']for r in json.loads(counts.read_bytes())}
    originals={(r['container'],tuple(r['names'])):r for r in json.loads(inventory.read_bytes())if r.get('recognition')=='mpeg_program_stream_undemuxed'}
    lines=['// Import-only File1 metadata; generated by make_file1_catalogue.py. No game payloads.']
    for r in rows:
        original=originals[(r['container'],tuple(r['names']))]
        if not r['complete']or r['audio_ids']or r['geometry']['rate']!=4 or r['sha256']!=original['sha256']:raise ValueError('Unqualified movie route')
        path='/'.join(r['names']);indices=[int(v)for v in original['member'].split('/')[1:]]
        values=[json.dumps(r['container']),json.dumps(path),str(r['source_offset']),str(r['bytes']),json.dumps(r['sha256']),str(pictures[tuple(r['names'])]),str(indices[0]),str(indices[-1])]
        lines.append('{'+','.join(values)+'},')
    if len(rows)!=201 or sum(pictures.values())!=216998:raise ValueError('Incomplete movie catalogue')
    out=Path(__file__).with_name('file1_movies.inc');out.write_text('\n'.join(lines)+'\n',encoding='utf-8',newline='\n')
    proof=dict(schema=1,movies=len(rows),pictures=sum(pictures.values()),inputs={p.relative_to(ROOT).as_posix():d for p,d in expected.items()},generator_sha256=sha(Path(__file__)),catalogue_sha256=sha(out),import_metadata_only=True,game_payloads_included=False)
    out.with_suffix('.json').write_text(json.dumps(proof,indent=2)+'\n',encoding='utf-8',newline='\n')
    print('Generated metadata for201 owned File1 movies; no game payloads.')
if __name__=='__main__':main()
