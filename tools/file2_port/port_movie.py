#!/usr/bin/env python3
"""Port the native GPU movie route from File #1 to File #2.

    python tools/file2_port/port_movie.py wrap      # one-time: wrap literals in handwritten sources
    python tools/file2_port/port_movie.py headers   # write per-game address headers
    python tools/file2_port/port_movie.py copies    # translate the copied functions for File #2

The handwritten movie sources name File #1 guest addresses through REO_MA(0x...) and
recompiled functions through REO_MS_<ADDR>; `reo_movie_game_addresses.h` (one per game)
supplies the values. File #1's header is the identity, so File #1 compiles unchanged.

The copied functions (original_transport_*.cpp and the movie callers/observers) are File #1
generated code plus inserted lines. Their File #1 ranges are byte-identical in File #2 apart
from call targets and data immediates, which this tool checks against both ELFs before
translating; the output goes to recomp/config/output_file2/movie_copies (game code, ignored).
"""
import argparse
import os
import re
import struct
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
sys.path.insert(0, os.path.dirname(__file__))
from translate import Translator  # noqa: E402

MOVIE = os.path.join(ROOT, "tools", "parallel_gs_backend", "movie_runtime")
OVERRIDES = os.path.join(ROOT, "recomp", "overrides")
HANDWRITTEN = [
    os.path.join(MOVIE, n) for n in (
        "compressed_movie_lineage.h", "native_movie_game.cpp", "native_movie_transport.h",
        "original_graphics_route.cpp", "original_transport_route.cpp", "original_transport_route.h")
] + [os.path.join(OVERRIDES, n) for n in ("movie_join_observer.h", "reo_gpu_movie_boundary.h")]
COPIES = [os.path.join(MOVIE, "original_transport_%s.cpp" % n)
          for n in ("1570d8", "16aea0", "170ae8", "170d90", "171880", "171920", "171d10", "174030")]
COPIES += [os.path.join(MOVIE, "original_player_caller.cpp")]
COPIES += [os.path.join(OVERRIDES, n) for n in (
    "movie_join_observed_caller.cpp", "reo_movie_commit_observed.cpp", "reo_movie_initialize_observed.cpp")]
NOT_ADDRESSES = {0x1FFFFFF, 0x1FEEEF0}  # physical mask; synthetic native wait PC
# Verified by hand: alignment word before 0x16AFC8 (both 00000000).
EXTRA = {0x16AFC4: 0x1BEC34}
LITERAL = re.compile(r"\b0x([0-9A-Fa-f]{5,8})(u?)\b")
SUB = re.compile(r"\bsub_([0-9A-F]{8})_0x([0-9a-f]+)\b")


def translator():
    return Translator(os.path.join(ROOT, "recomp", "config", "file2", "file1_to_file2.json"))


def to_file2(tr, address):
    if address in EXTRA:
        return EXTRA[address]
    values = {value for _image, value, _kind in tr.candidates(address)}
    if len(values) != 1:
        raise SystemExit("no unique File #2 address for %#x: %r" % (address, sorted(values)))
    return values.pop()


def is_address(value):
    return 0x100000 <= value < 0x2000000 and value not in NOT_ADDRESSES


def read(path):
    with open(path, encoding="utf-8", newline="") as stream:
        return stream.read()


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="") as stream:
        stream.write(text)


def sub_name(address):
    return "sub_%08X_0x%x" % (address, address)


def wrap():
    """Replace File #1 literals in handwritten sources with REO_MA/REO_MS_ forms."""
    for path in HANDWRITTEN:
        text = read(path)
        if "reo_movie_game_addresses.h" in text:
            continue
        text = SUB.sub(lambda m: "REO_MS_%s" % m.group(1)[2:] if m.group(1).startswith("00")
                       else m.group(0), text)
        text = LITERAL.sub(lambda m: "REO_MA(%s)" % m.group(0) if is_address(int(m.group(1), 16))
                           else m.group(0), text)
        newline = "\r\n" if "\r\n" in text else "\n"
        first = text.index(newline) + len(newline) if text.startswith("#pragma once") else 0
        text = text[:first] + '#include "reo_movie_game_addresses.h"' + newline + text[first:]
        write(path, text)
        print("wrapped", os.path.relpath(path, ROOT))


def headers():
    tr = translator()
    addresses, subs = set(), set()
    for path in HANDWRITTEN:
        text = read(path)
        addresses |= {int(m.group(1), 16) for m in re.finditer(r"REO_MA\(0x([0-9A-Fa-f]+)u?\)", text)}
        subs |= {int(m.group(1), 16) for m in re.finditer(r"\bREO_MS_([0-9A-F]{6})\b", text)}
    for game in ("file1", "file2"):
        mapping = {a: (a if game == "file1" else to_file2(tr, a)) for a in sorted(addresses | subs)}
        lines = [
            "// Generated by tools/file2_port/port_movie.py headers. Do not edit.",
            "// Guest addresses used by the native movie route, keyed by File #1 address.",
            "#pragma once",
            "#include <cstdint>",
            "constexpr uint32_t reo_movie_address(uint32_t file1) {",
            "    switch (file1) {",
        ]
        lines += ["    case 0x%06Xu: return 0x%06Xu;" % (a, mapping[a]) for a in sorted(addresses)]
        lines += [
            "    default: return 0xFFFFFFFFu; // unmapped: fails any comparison or registration",
            "    }",
            "}",
            "#define REO_MA(address) reo_movie_address(address)",
        ]
        lines += ["#define REO_MS_%06X %s" % (a, sub_name(mapping[a])) for a in sorted(subs)]
        out = os.path.join(OVERRIDES, "movie_addresses", game, "reo_movie_game_addresses.h")
        write(out, "\n".join(lines) + "\n")
        print("wrote", os.path.relpath(out, ROOT), len(addresses), "addresses", len(subs), "functions")


def elf_words(path):
    data = open(path, "rb").read()
    header, count = struct.unpack_from("<I", data, 0x1C)[0], struct.unpack_from("<H", data, 0x2C)[0]
    segments = [struct.unpack_from("<6I", data, header + i * 32) for i in range(count)]

    def word(address):
        for kind, offset, vaddr, _paddr, size, _memsz in segments:
            if kind == 1 and vaddr <= address < vaddr + size:
                return struct.unpack_from("<I", data, offset + address - vaddr)[0]
        raise SystemExit("address %#x outside %s" % (address, path))
    return word


def immediate_text(word):
    """How the recompiler prints an I-type immediate (lui: shifted half; others: sign-extended u32)."""
    value = word & 0xFFFF
    if word >> 26 == 0x0F:
        return "(uint32_t)%d << 16" % value
    return ", %d)" % (value if value < 0x8000 else value + 0xFFFF0000)


def translate_copy(tr, text, word1, word2):
    """Translate one copied File #1 function to File #2, checking every differing instruction."""
    rng = re.search(r"// Address: 0x([0-9a-f]+) - 0x([0-9a-f]+)", text)
    start, end = int(rng.group(1), 16), int(rng.group(2), 16)
    delta = to_file2(tr, start) - start
    patches = {}
    for pc in range(start, end, 4):
        a, b = word1(pc), word2(pc + delta)
        if a == b or (a >> 26) in (2, 3):  # j/jal targets are translated as code literals
            continue
        if (a >> 26) not in (0x09, 0x0F) or (a & 0xFFFF0000) != (b & 0xFFFF0000):
            raise SystemExit("%#x: unexpected instruction difference %08x/%08x" % (pc, a, b))
        patches[pc] = (a, b)

    def code_literal(m):
        value = int(m.group(1), 16)
        if not 0x100000 <= value < 0x400000:
            return m.group(0)
        upper = any(c.isupper() for c in m.group(1))
        return ("0x%X" if upper else "0x%x") % to_file2(tr, value) + m.group(2)

    out, current = [], None
    for line in text.split("\n"):
        head = re.match(r"(\s*// )0x([0-9a-f]+):(.*)", line)
        if head:
            current = int(head.group(2), 16)
            line = "%s0x%x:%s" % (head.group(1), current + delta, head.group(3))
            line = re.sub(r"func_([0-9A-F]{6})\b",
                          lambda m: "func_%06X" % to_file2(tr, int(m.group(1), 16)), line)
            if current in patches:
                a, b = patches[current]
                line = line.replace("0x%x " % a, "0x%x " % b, 1)
            out.append(line)
            continue
        code, sep, comment = line.partition("//")
        code = SUB.sub(lambda m: sub_name(to_file2(tr, int(m.group(1), 16))), code)
        code = LITERAL.sub(code_literal, code)
        if current in patches:
            a, b = patches[current]
            if immediate_text(a) in code:
                code = code.replace(immediate_text(a), immediate_text(b), 1)
                del patches[current]
        out.append(code + sep + comment)
    if patches:
        raise SystemExit("unpatched data instructions: %s" % ", ".join("%#x" % pc for pc in patches))
    return "\n".join(out)


def copies(out_dir):
    tr = translator()
    word1 = elf_words(os.path.join(ROOT, "game_data", "SLUS_207.65"))
    word2 = elf_words(os.path.join(ROOT, "game_data_file2", "SLUS_209.84"))
    for path in COPIES:
        name = os.path.basename(path)
        write(os.path.join(out_dir, name), translate_copy(tr, read(path).replace("\r\n", "\n"), word1, word2))
        print("translated", name)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("command", choices=("wrap", "headers", "copies"))
    parser.add_argument("--out", default=os.path.join(ROOT, "recomp", "config", "output_file2", "movie_copies"))
    args = parser.parse_args()
    {"wrap": wrap, "headers": headers, "copies": lambda: copies(args.out)}[args.command]()


if __name__ == "__main__":
    main()
