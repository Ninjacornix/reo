"""Extract File1's authored walk/run synchronization intervals."""
from pathlib import Path
import hashlib,struct
ROOT=Path(__file__).resolve().parents[2]
def main():
    raw=(ROOT/'build-function-index/owned-overlays/o2.bin').read_bytes()
    digest=hashlib.sha256(raw).hexdigest()
    assert digest=='45360a971e88878312576abaebd1a7b8346f7e94cc032adde9172343f14e6226'
    def unpack(at,fmt):return struct.unpack_from('<'+fmt,raw,at-0x570000)
    pointers=unpack(0x723d80,'16I');assert [i for i,p in enumerate(pointers) if p]==[1,4]
    lines=['// Generated by generate_locomotion_transition_profile.py; o2 SHA256 '+digest,
           'struct LocomotionIntervals {std::uint8_t count;std::array<std::array<std::int16_t,4>,5> rows;};',
           'constexpr std::array<std::array<LocomotionIntervals,8>,2> locomotion_intervals{{']
    for index in (1,4):
        lines.append('    {{')
        for character in range(8):
            ptr,count=unpack(pointers[index]+8*character,'II');assert ptr and count%2==0 and count<=10
            rows=[unpack(ptr+8*i,'4h') for i in range(count//2)]
            lines.append('        {'+str(count//2)+',{{'+','.join('{{'+','.join(map(str,row))+'}}' for row in rows)+'}}},')
        lines.append('    }},')
    lines.append('}};')
    values=[unpack(0x719a64+68*i,'B')[0] for i in range(64)]
    lines.append('constexpr std::array<std::uint8_t,64> locomotion_resource_classes{{'+','.join(map(str,values))+'}};')
    (ROOT/'game/native/gameplay_world/locomotion_transition_profile.inc').write_text('\n'.join(lines)+'\n')
if __name__=='__main__':main()
