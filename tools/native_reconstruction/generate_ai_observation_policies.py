"""Decode immutable character observation probabilities from the owned overlay."""
import hashlib
import struct
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
def generated():
    raw=(ROOT/'build-function-index/owned-overlays/o9.bin').read_bytes()
    assert hashlib.sha256(raw).hexdigest()=='604126d6edca1b1333948d79d1d2c8d2f2e22f4a233efbdfb769c106dafe7343'
    normal=struct.unpack_from('<8b',raw,0x828fa0-0x810000);room=struct.unpack_from('<8b',raw,0x828fa8-0x810000)
    factors=tuple(struct.unpack_from('<I',raw,a-0x810000)[0] for a in [0x82b4b8,0x82b4c0])
    assert factors==(0x3f333333,0x3fa66666)
    return ('// Owned File1 observation probabilities; generated by generate_ai_observation_policies.py.\n'
        'constexpr std::array<std::int8_t,8> reference_chances{'+','.join(map(str,normal))+'};\n'
        'constexpr std::array<std::int8_t,8> room_chances{'+','.join(map(str,room))+'};\n'
        'constexpr float self_weight_factor=std::bit_cast<float>(0x3f333333u),reference_weight_factor=std::bit_cast<float>(0x3fa66666u);\n')
if __name__=='__main__':
    (ROOT/'game/native/gameplay_ai/observation_policies.inc').write_text(generated())
