"""Extract the twenty immutable authored AI profiles from the owned overlay."""
import hashlib
from pathlib import Path

ROOT=Path(__file__).resolve().parents[2]


def profile_bytes():
    data=(ROOT/'build-function-index/owned-overlays/o9.bin').read_bytes()
    assert hashlib.sha256(data).hexdigest()=='604126d6edca1b1333948d79d1d2c8d2f2e22f4a233efbdfb769c106dafe7343'
    return data[0x828a60-0x810000:0x828a60-0x810000+20*56]


def generated():
    data=profile_bytes()
    rows=['// Owned File1 authored AI weight profiles; generated by generate_ai_weight_profiles.py.']
    for i in range(20):
        row=data[i*56:(i+1)*56]
        rows.append('    {{'+','.join(map(str,row[:8]))+'},{'+','.join(map(str,row[8:]))+'}},')
    return '\n'.join(rows)+'\n'


if __name__=='__main__':
    (ROOT/'game/native/gameplay_ai/weight_profiles.inc').write_text(generated())
