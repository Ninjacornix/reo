"""Decode the immutable stimulus/threat inputs used by owned812540."""
import hashlib
import struct
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
def generated():
    raw=(ROOT/'build-function-index/owned-overlays/o9.bin').read_bytes()
    assert hashlib.sha256(raw).hexdigest()=='604126d6edca1b1333948d79d1d2c8d2f2e22f4a233efbdfb769c106dafe7343'
    def read(at,fmt):return struct.unpack_from('<'+fmt,raw,at-0x810000)
    assert read(0x82b450,'12I')==(0x812ab0,0x81289c,0x8128cc,0x812ab0,0x812950,0x8129c8,0x812ab0,0x812ab0,0x812a30,0x8128b4,0x8128b4,0x812ab0)
    types=read(0x829d40,'64B');assert max(types)==6
    rows=['// Owned File1 observation policy; generated by generate_ai_observation_frame_policy.py.',
        'constexpr std::array<std::uint16_t,8> reactive_holds{'+','.join(map(str,read(0x828ec0,'8H')))+'};',
        'constexpr std::array<std::uint8_t,4> threat_bonuses{'+','.join(map(str,read(0x828f80,'4B')))+'};',
        'constexpr std::array<std::uint8_t,64> threat_types{'+','.join(map(str,types))+'};',
        'constexpr std::array<ThreatPolicy,7> threat_policies{{']
    for i in range(7):
        *distances,priority=read(0x828f60+4*i,'4b');rows.append('    {{'+','.join(map(str,distances))+'},'+str(priority)+'},')
    return '\n'.join(rows+['}};',''])
if __name__=='__main__':
    (ROOT/'game/native/gameplay_update/ai_observation_frame_policy.inc').write_text(generated())
