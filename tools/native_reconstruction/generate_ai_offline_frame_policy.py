"""Extract the immutable 8122B0 health/gauge policy from pinned File1 o9."""
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def generated():
    image = (ROOT / 'build-function-index/owned-overlays/o9.bin').read_bytes()
    assert hashlib.sha256(image).hexdigest() == '604126d6edca1b1333948d79d1d2c8d2f2e22f4a233efbdfb769c106dafe7343'
    policy = image[0x828ed0 - 0x810000:0x828ed0 - 0x810000 + 144]
    assert len(policy) == 144 and set(policy) <= {0, 1}
    rows = ['// File1 828ED0, generated by generate_ai_offline_frame_policy.py.',
            'constexpr std::array<std::array<std::uint8_t,9>,16> offline_policy{{']
    for i in range(16):
        rows.append('    {{' + ','.join(map(str, policy[9*i:9*i+9])) + '}},')
    return '\n'.join(rows + ['}};', ''])


if __name__ == '__main__':
    (ROOT / 'game/native/gameplay_application/ai_offline_frame_policy.inc').write_text(generated())
