"""Decode owned reaction policy values without retaining guest pointer tables."""
import hashlib
import struct
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]

def generated():
    raw=(ROOT/'build-function-index/owned-overlays/o9.bin').read_bytes()
    assert hashlib.sha256(raw).hexdigest()=='604126d6edca1b1333948d79d1d2c8d2f2e22f4a233efbdfb769c106dafe7343'
    jumps=struct.unpack_from('<13I',raw,0x82b480-0x810000)
    assert jumps==(0x813110,)*5+(0x8131cc,)*4+(0x813110,)*3+(0x8132e4,)
    pointers=struct.unpack_from('<13I',raw,0x829480-0x810000)
    assert pointers==tuple(range(0x828fb0,0x829010,8))+(0,)
    rows=['// Owned File1 reaction policies; generated by generate_ai_reaction_policies.py.']
    for index,pointer in enumerate(pointers):
        duration,reaction,auxiliary=struct.unpack_from('<3b',raw,0x829450-0x810000+3*index)
        chances=struct.unpack_from('<8b',raw,pointer-0x810000) if pointer else (0,)*8
        rows.append('    {'+','.join(map(str,[duration,reaction,auxiliary]))+',{'+','.join(map(str,chances))+'}},')
    return '\n'.join(rows)+'\n'

if __name__=='__main__':
    (ROOT/'game/native/gameplay_ai/reaction_policies.inc').write_text(generated())
