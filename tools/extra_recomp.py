#!/usr/bin/env python3
"""Recompile extra main-ELF entry points into recomp/config/output_extra/ without touching
the main output (whose shared header would force a full rebuild).

Use for functions the Ghidra map merged into a neighbour, e.g. pointer-table targets inside
a larger mapped range. Input: recomp/config/extra_functions.csv (name,start,end,size), each
row a real function start. Generated names get the `x_` prefix; reoRegisterExtraFunctions()
registers them (after the main table) with PS2Runtime::registerFunction.

Usage: extra_recomp.py <recomp_exe> [<elf>]
"""
import csv
import os
import re
import struct
import subprocess
import sys
import time

OUT = os.path.join('recomp', 'config', 'output_extra')
MAP = os.path.join('recomp', 'config', 'extra_functions.csv')


def main():
    exe = sys.argv[1]
    elf = sys.argv[2] if len(sys.argv) > 2 else os.path.join('game_data', 'SLUS_207.65')
    rows = list(csv.DictReader(open(MAP)))
    for r in rows:
        r['name'] = 'x_' + re.sub(r'^(sub|FUN)_', '', r['name'])
    work = os.path.abspath(os.path.join('build-ninja', 'extra_recomp'))
    os.makedirs(work, exist_ok=True)
    # ps2_recomp registers the ELF entry function: point the entry at the first extra function.
    img = bytearray(open(elf, 'rb').read())
    struct.pack_into('<I', img, 24, int(rows[0]['start'], 16))
    elf2 = os.path.join(work, 'main_extra.elf')
    open(elf2, 'wb').write(img)
    map2 = os.path.join(work, 'extra.csv')
    with open(map2, 'w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=['name', 'start', 'end', 'size'])
        w.writeheader()
        w.writerows(rows)
    out = os.path.abspath(OUT)
    os.makedirs(out, exist_ok=True)
    for old in os.listdir(out):
        for _ in range(20):
            try:
                os.remove(os.path.join(out, old))
                break
            except PermissionError:
                time.sleep(0.25)
    toml = os.path.join(work, 'extra.toml')
    with open(toml, 'w') as f:
        f.write('[general]\ninput = "%s"\nghidra_output = "%s"\noutput = "%s/"\nsingle_file_output = false\n'
                'patch_syscalls = false\npatch_cop0 = true\npatch_cache = true\n'
                % (elf2.replace('\\', '/'), map2.replace('\\', '/'), out.replace('\\', '/')))
    subprocess.run([exe, toml], check=True, stdout=subprocess.DEVNULL)

    # The ELF's other functions are generated too (the recompiler scans the whole ELF);
    # keep only the requested ones and their resumable entries.
    ranges = [(int(r['start'], 16), int(r['end'], 16)) for r in rows]
    inside = lambda a: any(s <= a < e for s, e in ranges)
    reg = open(os.path.join(out, 'register_functions.cpp')).read()
    calls = [(int(a, 16), fn) for a, fn in re.findall(r'runtime\.registerFunction\((0x[0-9a-fA-F]+), (\w+)\);', reg)]
    keep_fns = {fn for a, fn in calls if inside(a)}
    for name in os.listdir(out):
        if name.endswith('.cpp') and name != 'register_functions.cpp':
            if not any(name.startswith(fn.rsplit('_0x', 1)[0]) for fn in keep_fns):
                os.remove(os.path.join(out, name))
    hdr = open(os.path.join(out, 'ps2_recompiled_functions.h')).read()
    hdr = hdr.replace('PS2_RECOMPILED_FUNCTIONS_H', 'REO_EXTRA_FUNCTIONS_H')
    open(os.path.join(out, 'extra_functions.h'), 'w').write(hdr)
    os.remove(os.path.join(out, 'ps2_recompiled_functions.h'))
    for name in os.listdir(out):
        if name.endswith('.cpp'):
            p = os.path.join(out, name)
            c = open(p).read().replace('#include "ps2_recompiled_functions.h"', '#include "extra_functions.h"')
            open(p, 'w').write(c)
    os.remove(os.path.join(out, 'register_functions.cpp'))
    with open(os.path.join(out, 'register_extra.cpp'), 'w') as f:
        f.write('// Generated by tools/extra_recomp.py from recomp/config/extra_functions.csv.\n'
                '#include "ps2_runtime.h"\n#include "extra_functions.h"\n\n'
                'void reoRegisterExtraFunctions(PS2Runtime& runtime) {\n')
        n = 0
        for a, fn in calls:
            if inside(a):
                f.write('    runtime.registerFunction(0x%Xu, %s);\n' % (a, fn))
                n += 1
        f.write('}\n')
    print('extra: %d functions, %d registrations, %d sources -> %s' % (
        len(rows), n, len([x for x in os.listdir(out) if x.endswith('.cpp')]), out))


if __name__ == '__main__':
    main()
