"""Regenerate the embedded ordered 4x scanout shader from the pinned GS shader.

Usage: python build_scanout.py --glslang PATH --validator PATH
The resulting header is checked in; user builds need no shader compiler here.
"""
import argparse
from pathlib import Path
import subprocess
import tempfile


def build(glslang, validator):
    here = Path(__file__).resolve().parent
    root = here.parents[3]
    upstream = root / "build-ninja/parallel-gs-source/gs/shaders"
    source = (upstream / "sample_circuit.frag").read_text()
    # Retain the original bindings, pixel formats and validity handling. Each
    # output pixel fetches one sample of the renderer's ordered 4x4 grid.
    start = source.index("void main()")
    source = source[:start] + '''// Ordered 4x4 scanout; see compute_sample_points in gs_renderer.cpp.
void main()
{
    uvec2 output_coord = uvec2(gl_FragCoord.xy);
    uvec2 coord = (output_coord >> (SUPER_SAMPLES == 16 ? 2u : 0u)) *
        uvec2(1u, registers.phase_stride) + uvec2(registers.dbx, registers.dby + registers.phase);
#if PROMOTED
    #define addr coord
    const uint BASE_SSAA_LAYER = 1;
#else
    uint addr = swizzle_PS2(coord.x, coord.y, registers.fbp * PGS_BLOCKS_PER_PAGE,
                           registers.fbw, PSM, VRAM_MASK);
    const uint BASE_SSAA_LAYER = 2;
#endif
    // Interleave low y/x bits, then high y/x bits, matching GS sample storage.
    uint sample_id = (output_coord.y & 1u) | ((output_coord.x & 1u) << 1u) |
                     ((output_coord.y & 2u) << 1u) | ((output_coord.x & 2u) << 2u);
    FragColor = SUPER_SAMPLES == 16 && super_sample_is_valid(addr)
        ? sample_vram(addr, BASE_SSAA_LAYER + sample_id) : sample_vram(addr, 0);
}
'''
    source = source.replace("#version 450", "#version 450\n#extension GL_GOOGLE_include_directive : require")
    header = "// Generated by shaders/build_scanout.py from pinned LGPL-3.0+ sample_circuit.frag.\n#pragma once\n#include <cstddef>\n#include <cstdint>\nnamespace reo_scanout4 {\n"
    with tempfile.TemporaryDirectory(prefix="reo-scanout-") as temp:
        folder = Path(temp)
        fragment = folder / "sample_circuit_4x.frag"
        fragment.write_text(source)
        for promoted in (0, 1):
            binary = folder / f"scanout{promoted}.spv"
            subprocess.run([str(glslang), "-V", "--target-env", "vulkan1.1", "-Os",
                            "-I" + str(upstream), "-I" + str(upstream / "../../Granite/assets/shaders/inc"),
                            f"-DPROMOTED={promoted}", "-o", str(binary), str(fragment)], check=True)
            subprocess.run([str(validator), "--target-env", "vulkan1.1", str(binary)], check=True)
            data = binary.read_bytes()
            header += f"alignas(4) inline constexpr unsigned char shader{promoted}[] = {{\n"
            for offset in range(0, len(data), 24):
                header += "    " + ",".join(f"0x{v:02x}" for v in data[offset:offset+24]) + ",\n"
            header += "};\n"
    header += "inline constexpr const unsigned char* code[2]={shader0,shader1};\ninline constexpr std::size_t size[2]={sizeof(shader0),sizeof(shader1)};\n}\n"
    (here.parent / "scanout_spirv.hpp").write_text(header)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--glslang", required=True, type=Path)
    parser.add_argument("--validator", required=True, type=Path)
    args = parser.parse_args()
    build(args.glslang, args.validator)
