#!/usr/bin/env python3
"""Reproduce adapter3 from the frozen cohort2; never edits the parent cohort."""
import argparse
import hashlib
import json
from pathlib import Path

HERE=Path(__file__).resolve().parent
PARENT=HERE.parent
PIN='2d7efe5f594096d8e1083214341451bde5aa4396d1b7b37750c0a594e9f66616'
FILES=('packet_adapter.h','packet_adapter.cpp','backend_status.h','test_capture.h',
       'packet_adapter_tests.cpp','compare_original.py')
def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
def replace(text,old,new):
    if text.count(old)!=1:raise ValueError('Pinned derivation location changed: '+old[:80])
    return text.replace(old,new)
def derived(name):
    text=(PARENT/name).read_text(encoding='utf-8')
    text=text.replace('reo::native::bank_packets','reo::native::bank_packets::v3')
    text=text.replace('../../../game/','../../../../game/')
    if name=='packet_adapter.h':
        text=replace(text,'enum class Part {hd,bd,tq};','''enum class Part {hd,bd,tq};
// Versioned grouped-copy protocol. All destinations are already budgeted owned
// vectors. The provider must retain ONE qualified coherent read scope across
// every part and return only after that scope is released. No pointers retained.
enum class CopySourceV1 {ram,direct_hd,bd,tq};
struct PartCopyV1 {CopySourceV1 source;std::size_t offset;std::span<std::uint8_t> destination;};''')
        text=replace(text,'virtual bool copy_ram(std::size_t offset,std::span<std::uint8_t>)const noexcept=0;',
            'virtual bool copy_ram(std::size_t,std::span<std::uint8_t>)const noexcept{return false;}')
        text=replace(text,'virtual bool copy_bank(Part,std::span<std::uint8_t>)const noexcept=0;',
            '''virtual bool copy_bank(Part,std::span<std::uint8_t>)const noexcept{return false;}
    // No fallback to independent-part methods, even if those are implemented.
    virtual Status copy_parts_v1(std::span<const PartCopyV1>)const noexcept{return Status::unsupported;}''')
    elif name=='packet_adapter.cpp':
        start=text.index('    for(unsigned n=0;n<3;++n){\n        status=source_status(s,source);')
        end=text.index('    auto prepared=',start)
        text=text[:start]+'''    std::array<PartCopyV1,3> copies{};
    for(unsigned n=0;n<3;++n)copies[n]={offsets?CopySourceV1::ram:CopySourceV1(unsigned(CopySourceV1::direct_hd)+n),offsets?(*offsets)[n]:0,parts[n]};
    status=source_status(s,source);if(status!=Status::ok)return status;
    const auto copied=source.copy_parts_v1(copies); // ONE group; released on return, before decode.
    status=source_status(s,source);if(status!=Status::ok)return status;
    if(copied!=Status::ok)return copied;
'''+text[end:]
    elif name=='test_capture.h':
        text=replace(text,'    bool copy_bank(p::Part part,std::span<std::uint8_t> out)const noexcept override {',
            '''    // Immutable fixture bytes only. This explicit batch override preserves
    // historical fixture barriers/counts; it is NOT production RAM qualification.
    p::Status copy_parts_v1(std::span<const p::PartCopyV1> parts)const noexcept override {
        ++group_reads;
        for(const auto& part:parts){
            const bool copied=part.source==p::CopySourceV1::ram?copy_ram(part.offset,part.destination):
                copy_bank(p::Part(unsigned(part.source)-unsigned(p::CopySourceV1::direct_hd)),part.destination);
            if(!copied)return p::Status::capture_failed;
        }
        return p::Status::ok;
    }
    mutable std::atomic<unsigned> group_reads{};
    bool copy_bank(p::Part part,std::span<std::uint8_t> out)const noexcept override {''')
    elif name=='compare_original.py':
        text=text.replace('ROOT=HERE.parents[2]','ROOT=HERE.parents[3]')
        text=text.replace('native-bank-packet-adapter','native-bank-group-capture')
        text=text.replace("p.suffix in ('.cpp','.h','.py')","p.suffix in ('.cpp','.h','.hpp','.py')")
    return '// Generated by derive.py from pinned adapter cohort2; grouped capture only.\n'+text if not name.endswith('.py') else text
def check_parent():
    if sha(PARENT/'identity.json')!=PIN:raise ValueError('Frozen parent identity changed')
    identity=json.loads((PARENT/'identity.json').read_bytes())
    for name,digest in identity['candidate_sha256'].items():
        if sha(PARENT/name)!=digest:raise ValueError('Frozen parent source changed: '+name)
def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args();check_parent()
    for name in FILES:
        expected=derived(name)
        if a.check:
            if (HERE/name).read_text(encoding='utf-8')!=expected:raise ValueError('Generated adapter drift '+name)
        else:(HERE/name).write_text(expected,encoding='utf-8',newline='\n')
    print('adapter3 derivation '+('checked' if a.check else 'written'))
if __name__=='__main__':main()
